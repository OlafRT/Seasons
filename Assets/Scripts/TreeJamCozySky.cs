using System;
using UnityEngine;

namespace TreeJam
{
    /// <summary>
    /// An animated 2D sky, compatible with Unity's URP 2D Renderer.
    /// Replaces ONLY the displayed day/night background sprites during Play Mode.
    /// Does not change sun motion, the actual clock, seasons or photosynthesis.
    /// </summary>
    [DisallowMultipleComponent]
    [DefaultExecutionOrder(6000)]
    public sealed class TreeJamCozySky : MonoBehaviour
    {
        [Header("Existing scene references")]
        public TreeJamDayNightCycle clock;
        public TreeJamSeasonCycle seasons;
        public SpriteRenderer oldDaySky;
        public SpriteRenderer oldNightSky;
        [Tooltip("Generated by the installer; not an artwork asset.")]
        public SpriteRenderer generatedSky;

        [Header("Day / sunset / night palette (editable!)")]
        public Color dayTop = new Color(.28f, .63f, .91f);
        public Color dayHorizon = new Color(.87f, .95f, .99f);
        public Color twilightTop = new Color(.30f, .32f, .62f);
        public Color twilightHorizon = new Color(1f, .60f, .43f);
        public Color nightTop = new Color(.025f, .042f, .105f);
        public Color nightHorizon = new Color(.13f, .16f, .29f);

        [Header("Transition")]
        [Tooltip("How many in-game clock hours twilight begins before sunrise / ends after sunset.")]
        [Range(.2f, 4f)] public float twilightHours = 1.9f;
        [Tooltip("Extra seasonal pink/purple in winter dawn and dusk.")]
        [Range(0f, 1f)] public float winterTwilightPink = .25f;
        [Range(0f, 1f)] public float sunsetWarmth = .9f;

        [Header("Sunset Position (not the GameObject transform)")]
        [Tooltip("Raise the sunset / sunrise color band above the mountains without moving or cropping the sky sprite. 0 = at texture bottom, 0.5 = halfway up. Adjust during Play Mode while previewing sunset.")]
        [Range(0f, 0.75f)] public float sunsetHeight = .27f;
        [Tooltip("How far the bright sunset glow spreads upward from the sunset height. Larger values = taller, softer sunsets.")]
        [Range(.05f, .7f)] public float sunsetGlowSpread = .23f;

        [Header("Atmosphere")]
        [Range(0f, 1f)] public float cloudAmount = .23f;
        [Range(0f, 3f)] public float cloudDrift = .32f;
        [Range(0, 180)] public int stars = 95;
        [Range(0f, 2f)] public float starVisibility = 1f;
        [Range(0f, 1f)] public float horizonGlow = .35f;
        [Range(2, 24)] public int updatesPerSecond = 10;
        [Header("Testing only")]
        [Tooltip("Preview the sky at any hour in Play Mode. Doesn't change gameplay time.")]
        public bool previewHourInsteadOfClock;
        [Range(0f, 24f)] public float previewHour = 19f;

        private Texture2D skyTexture;
        private Sprite skySprite;
        private Material skyMaterial;
        private Color32[] pixels;
        private Star[] starPositions;
        private float nextUpdate;
        private bool wasDaySkyEnabled;
        private bool wasNightSkyEnabled;
        private Bounds skyBounds;
        private bool initialized;
        private const int Width = 384;
        private const int Height = 216;

        private struct Star { public int x, y; public float phase, brightness; }

        private void Awake()
        {
            if (clock == null) clock = FindFirstObjectByType<TreeJamDayNightCycle>();
            if (seasons == null) seasons = FindFirstObjectByType<TreeJamSeasonCycle>();
            if (oldDaySky == null || generatedSky == null || clock == null)
            {
                Debug.LogWarning("Cozy Sky: Assign the original Day Sky, Generated Sky and Day/Night Clock. No background was changed.", this);
                enabled = false;
                return;
            }

            // Capture original render states BEFORE hiding anything.
            wasDaySkyEnabled = oldDaySky.enabled;
            if (oldNightSky != null) wasNightSkyEnabled = oldNightSky.enabled;
            skyBounds = oldDaySky.bounds;
            if (skyBounds.size.x < .01f || skyBounds.size.y < .01f)
            {
                Debug.LogWarning("Cozy Sky: Day Sky has no usable sprite bounds.", this);
                enabled = false;
                return;
            }
            skyTexture = new Texture2D(Width, Height, TextureFormat.RGBA32, false);
            skyTexture.name = "Cozy 2D Sky (runtime)";
            skyTexture.wrapMode = TextureWrapMode.Clamp;
            skyTexture.filterMode = FilterMode.Bilinear;
            pixels = new Color32[Width * Height];
            skySprite = Sprite.Create(skyTexture, new Rect(0f, 0f, Width, Height), new Vector2(.5f, .5f), 100f);
            skySprite.name = "Cozy 2D Sky Sprite (runtime)";
            Shader unlit = Shader.Find("Universal Render Pipeline/2D/Sprite-Unlit-Default");
            if (unlit == null) unlit = Shader.Find("Sprites/Default");
            if (unlit != null)
            {
                skyMaterial = new Material(unlit);
                skyMaterial.name = "Cozy Sky Unlit (runtime)";
                generatedSky.sharedMaterial = skyMaterial;
            }
            generatedSky.sprite = skySprite;
            generatedSky.sortingLayerID = oldDaySky.sortingLayerID;
            generatedSky.sortingOrder = oldDaySky.sortingOrder;
            generatedSky.color = Color.white;
            BuildStars();
            PositionSky();
            generatedSky.enabled = true;
            oldDaySky.enabled = false;
            if (oldNightSky != null) oldNightSky.enabled = false;
            initialized = true;
            RenderSky();
        }

        private void LateUpdate()
        {
            if (!initialized) return;
            // The existing Nordic sky component is still allowed to update summer
            // photosynthesis, but its two old background sprites remain hidden.
            oldDaySky.enabled = false;
            if (oldNightSky != null) oldNightSky.enabled = false;
            PositionSky();
            if (Time.unscaledTime < nextUpdate) return;
            nextUpdate = Time.unscaledTime + 1f / Mathf.Max(2, updatesPerSecond);
            RenderSky();
        }

        private void PositionSky()
        {
            if (generatedSky == null || skySprite == null) return;
            generatedSky.transform.position = new Vector3(skyBounds.center.x, skyBounds.center.y, oldDaySky.transform.position.z);
            Vector2 size = skySprite.bounds.size;
            generatedSky.transform.localScale = new Vector3(skyBounds.size.x / size.x, skyBounds.size.y / size.y, 1f);
        }

        private static float Ease(float value)
        {
            float t = Mathf.Clamp01(value);
            return t * t * (3f - 2f * t);
        }

        private static float Window(float hour, float start, float end)
        {
            return Ease((hour - start) / Mathf.Max(.05f, end - start));
        }

        private void RenderSky()
        {
            if (skyTexture == null || clock == null) return;
            float hour = previewHourInsteadOfClock ? previewHour : clock.CurrentHour;
            float sunrise = clock.sunriseHour;
            float sunset = clock.sunsetHour;
            float twilight = Mathf.Max(.2f, twilightHours);
            float daylight = Window(hour, sunrise - twilight, sunrise + twilight * .55f) *
                            (1f - Window(hour, sunset - twilight * .55f, sunset + twilight));
            float sunriseGlow = Mathf.Exp(-Mathf.Pow((hour - sunrise) / (twilight * .9f), 2f));
            float sunsetGlow = Mathf.Exp(-Mathf.Pow((hour - sunset) / (twilight * .9f), 2f));
            float warm = Mathf.Clamp01((sunriseGlow + sunsetGlow) * sunsetWarmth);
            Color top = Color.Lerp(nightTop, dayTop, daylight);
            Color horizon = Color.Lerp(nightHorizon, dayHorizon, daylight);
            top = Color.Lerp(top, twilightTop, warm * .80f);
            Color warmHorizon = twilightHorizon;
            if (seasons != null && seasons.CurrentSeason == TreeSeason.Winter)
                warmHorizon = Color.Lerp(warmHorizon, new Color(1f, .56f, .80f), winterTwilightPink);
            horizon = Color.Lerp(horizon, warmHorizon, warm * .95f);
            float starAlpha = Mathf.Clamp01((1f - daylight) * starVisibility);
            float drift = Time.time * cloudDrift * .045f;
            float sunX = hour <= sunrise ? 0f : (hour >= sunset ? 1f : Mathf.InverseLerp(sunrise, sunset, hour));
            sunX = Mathf.Lerp(sunX, .5f, daylight * .12f);

            // Low-resolution procedurally shaded texture, smoothly bilinear-filtered.
            for (int y = 0; y < Height; y++)
            {
                float v = (float)y / (Height - 1);
                // The texture always fills the original sky bounds. Moving its Transform
                // would uncover edges, so these parameters move the COLOR horizon instead.
                float raisedV = Mathf.Clamp01((v - sunsetHeight) / Mathf.Max(.1f, 1f - sunsetHeight));
                Color row = Color.Lerp(horizon, top, Mathf.Pow(raisedV, .76f));
                // Warm light reaches above the visible mountain silhouettes rather than
                // being concentrated at the very bottom of the sky texture.
                float aboveBand = Mathf.Max(0f, v - sunsetHeight);
                float lowHorizon = Mathf.Exp(-aboveBand / Mathf.Max(.05f, sunsetGlowSpread));
                for (int x = 0; x < Width; x++)
                {
                    float u = (float)x / (Width - 1);
                    Color c = row;
                    if (warm > .005f && horizonGlow > 0f)
                    {
                        float d = (u - sunX) / .40f;
                        float glow = Mathf.Exp(-d * d * 2.0f) * lowHorizon * warm * horizonGlow;
                        c = Color.Lerp(c, warmHorizon, glow);
                    }
                    if (cloudAmount > 0f && v > .33f && v < .88f)
                    {
                        // Two slow moving overlapping waves produce soft wispy clouds.
                        float wave = Mathf.Sin(u * 21f + drift + Mathf.Sin(v * 17f) * 1.1f) * .48f +
                                     Mathf.Sin(u * 37f - drift * .62f + v * 13f) * .26f;
                        float band = Mathf.Sin(Mathf.PI * Mathf.Clamp01((v - .33f) / .55f));
                        float cloud = Ease((wave - .16f) * 2.1f) * band * cloudAmount;
                        c = Color.Lerp(c, daylight > .4f ? Color.white : new Color(.45f, .48f, .64f), cloud * .65f);
                    }
                    pixels[y * Width + x] = c;
                }
            }
            if (starAlpha > .005f && starPositions != null)
            {
                for (int i = 0; i < starPositions.Length; i++)
                {
                    Star s = starPositions[i];
                    float flicker = .72f + .28f * Mathf.Sin(Time.time * .95f + s.phase);
                    float a = starAlpha * s.brightness * flicker;
                    BlendStar(s.x, s.y, a);
                    if (s.brightness > .8f)
                    {
                        BlendStar(s.x - 1, s.y, a * .18f);
                        BlendStar(s.x + 1, s.y, a * .18f);
                        BlendStar(s.x, s.y - 1, a * .18f);
                        BlendStar(s.x, s.y + 1, a * .18f);
                    }
                }
            }
            skyTexture.SetPixels32(pixels);
            skyTexture.Apply(false, false);
        }

        private void BlendStar(int x, int y, float opacity)
        {
            if (x < 0 || x >= Width || y < 0 || y >= Height) return;
            int index = y * Width + x;
            Color background = pixels[index];
            Color star = new Color(.86f, .93f, 1f);
            pixels[index] = Color.Lerp(background, star, Mathf.Clamp01(opacity));
        }

        private void BuildStars()
        {
            System.Random random = new System.Random(17321);
            starPositions = new Star[Mathf.Clamp(stars, 0, 180)];
            for (int i = 0; i < starPositions.Length; i++)
            {
                starPositions[i] = new Star
                {
                    x = random.Next(2, Width - 2),
                    y = random.Next(25, Height - 2),
                    phase = (float)random.NextDouble() * 6.2831853f,
                    brightness = Mathf.Lerp(.4f, 1f, (float)random.NextDouble())
                };
            }
        }

        private void OnDisable()
        {
            if (oldDaySky != null && initialized) oldDaySky.enabled = wasDaySkyEnabled;
            if (oldNightSky != null && initialized) oldNightSky.enabled = wasNightSkyEnabled;
            if (generatedSky != null) generatedSky.enabled = false;
            if (skySprite != null) Destroy(skySprite);
            if (skyTexture != null) Destroy(skyTexture);
            if (skyMaterial != null) Destroy(skyMaterial);
            skySprite = null;
            skyTexture = null;
            skyMaterial = null;
            initialized = false;
        }
    }
}
